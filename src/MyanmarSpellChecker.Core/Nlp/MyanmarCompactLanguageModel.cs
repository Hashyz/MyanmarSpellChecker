        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public static ulong ComputeWordHash(string normWord)
        {
            if (string.IsNullOrEmpty(normWord))
                return 0UL;
            ulong h = FnvOffsetBasis;
            for (int i = 0; i < normWord.Length; i++)
            {
                h ^= normWord[i];
                h *= FnvPrime;
            }
            return h == 0UL ? 1UL : h;
        }

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public static ulong ComputeTokenSliceHash(IReadOnlyList<SyllableToken> tokens, int startIndex, int count)
        {
            if (count <= 0)
                return 0UL;
            ulong h = FnvOffsetBasis;
            int end = startIndex + count;
            for (int t = startIndex; t < end; t++)
            {
                string s = tokens[t].NormalizedText;
                for (int i = 0; i < s.Length; i++)
                {
                    h ^= s[i];
                    h *= FnvPrime;
                }
            }
            return h == 0UL ? 1UL : h;
        }

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public static ulong CombineBigramHash(ulong leftWordHash, ulong rightWordHash)
        {
            if (leftWordHash == 0UL || rightWordHash == 0UL)
                return 0UL;
            ulong h = leftWordHash ^ 0x9E3779B97F4A7C15UL;
            h *= FnvPrime;
            h ^= rightWordHash;
            h *= FnvPrime;
            return h == 0UL ? 1UL : h;
        }

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public static double GetPosBigramLogProb(MyanmarUposTag prevTag, MyanmarUposTag curTag)
        {
            int idx = (((int)prevTag & 0xF) << 4) | ((int)curTag & 0xF);
            return s_posBigramLog10x[idx] * 0.1;
        }

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public static double GetPosTrigramLogProb(MyanmarUposTag prevPrevTag, MyanmarUposTag prevTag, MyanmarUposTag curTag)
        {
            int idx = (((int)prevPrevTag & 0xF) << 8) | (((int)prevTag & 0xF) << 4) | ((int)curTag & 0xF);
            return s_posTrigramLog10x[idx] * 0.1;
        }

        /// <summary>
        /// Converts POS transition log-probability into a centered, bounded Viterbi cost delta [-0.14 .. +0.18]
        /// so natural grammatical sequences (e.g. ADV->VERB, VERB->PRT, ADJ->NOUN, NOUN->ADP) win ties cleanly
        /// without overpowering lexical orthography rules.
        /// </summary>
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public static double GetViterbiPosStepDelta(MyanmarUposTag prevPrevTag, MyanmarUposTag prevTag, MyanmarUposTag curTag)
        {
            if (curTag == MyanmarUposTag.Unk || prevTag == MyanmarUposTag.Unk)
                return 0.0;

            double logP = prevPrevTag != MyanmarUposTag.Unk
                ? GetPosTrigramLogProb(prevPrevTag, prevTag, curTag)
                : GetPosBigramLogProb(prevTag, curTag);

            // Baseline neutral logP ~ -2.2: transitions stronger than -2.2 get negative cost (bonus), improbable transitions (< -4.5) get mild penalty
            double delta = (-2.2 - logP) * 0.032;
            if (delta < -0.14) return -0.14;
            if (delta > 0.18) return 0.18;
            return delta;
        }

        public static MyanmarUposTag ResolveUposTagFromEntries(List<DictionaryEntry>? entries, string? firstSyl = null, string? lastSyl = null)
        {
            if (entries != null && entries.Count > 0)
            {
                // Prefer unambiguous closed-class & POS tags across homographs
                for (int i = 0; i < entries.Count; i++)
                {
                    string w = entries[i].Word;
                    if (ConjWords.Contains(w)) return MyanmarUposTag.Conj;
                    if (AdpPostpositions.Contains(w)) return MyanmarUposTag.Adp;
                    if (PrtParticles.Contains(w)) return MyanmarUposTag.Prt;
                    if (PronWords.Contains(w)) return MyanmarUposTag.Pron;
                    if (DetAndNumWords.Contains(w)) return MyanmarUposTag.Num;
                }

                string pt = entries[0].PosTag ?? string.Empty;
                MyanmarUposTag mapped = MapLexiconPosString(pt);
                if (mapped != MyanmarUposTag.Unk)
                    return mapped;
            }

            if (!string.IsNullOrEmpty(lastSyl))
            {
                if (lastSyl == "စွာ") return MyanmarUposTag.Adv;
                if (lastSyl == "မှု" || lastSyl == "ခြင်း" || lastSyl == "ချက်" || lastSyl == "ရေး") return MyanmarUposTag.Noun;
            }
            if (!string.IsNullOrEmpty(firstSyl))
            {
                if (firstSyl == "အ" && !string.IsNullOrEmpty(lastSyl) && lastSyl != "အ")
                    return MyanmarUposTag.Noun;
                if (firstSyl == "မ")
                    return MyanmarUposTag.Verb;
            }

            return MyanmarUposTag.Unk;
        }

        public static MyanmarUposTag ResolveWordUposTag(string normWord, MyanmarTrie? trie)
        {
            if (string.IsNullOrEmpty(normWord))
                return MyanmarUposTag.Unk;

            if (ConjWords.Contains(normWord)) return MyanmarUposTag.Conj;
            if (AdpPostpositions.Contains(normWord)) return MyanmarUposTag.Adp;
            if (PrtParticles.Contains(normWord)) return MyanmarUposTag.Prt;
            if (PronWords.Contains(normWord)) return MyanmarUposTag.Pron;
            if (DetAndNumWords.Contains(normWord)) return MyanmarUposTag.Num;

            if (normWord.EndsWith("စွာ", StringComparison.Ordinal) && normWord.Length >= 4)
                return MyanmarUposTag.Adv;
            if ((normWord.EndsWith("မှု", StringComparison.Ordinal) || normWord.EndsWith("ခြင်း", StringComparison.Ordinal)) && normWord.Length >= 4)
                return MyanmarUposTag.Noun;

            if (trie != null && trie.TryGetExactEntries(normWord, out var entries) && entries != null && entries.Count > 0)
            {
                return ResolveUposTagFromEntries(entries);
            }

            if (normWord.Length >= 1 && normWord[0] >= '\u1040' && normWord[0] <= '\u1049')
                return MyanmarUposTag.Num;

            return MyanmarUposTag.Unk;
        }

        private static MyanmarUposTag MapLexiconPosString(string pos)
        {
            if (string.IsNullOrEmpty(pos))
                return MyanmarUposTag.Unk;

            if (pos == "N" || pos == "NOUN" || pos == "LOAN" || pos.StartsWith("N/", StringComparison.Ordinal))
                return MyanmarUposTag.Noun;
            if (pos == "PROPN")
                return MyanmarUposTag.Propn;
            if (pos == "PRON")
                return MyanmarUposTag.Pron;
            if (pos == "V" || pos == "VERB" || pos.StartsWith("V/", StringComparison.Ordinal))
                return MyanmarUposTag.Verb;
            if (pos == "ADJ")
                return MyanmarUposTag.Adj;
            if (pos == "ADV")
                return MyanmarUposTag.Adv;
            if (pos == "PART" || pos == "PRT" || pos == "CLF")
                return MyanmarUposTag.Prt;
            if (pos == "POSTP" || pos == "ADP" || pos == "PREP")
                return MyanmarUposTag.Adp;
            if (pos == "CONJ")
                return MyanmarUposTag.Conj;
            if (pos == "NUM")
                return MyanmarUposTag.Num;
            if (pos == "INTJ")
                return MyanmarUposTag.Intj;

            return MyanmarUposTag.Unk;
        }

        /// <summary>
        /// Returns true when an issue represents a widespread informal/colloquial/classical orthographic variant
        /// that should be tolerated in <see cref="ProofingStyleMode.ColloquialPermissive"/> (or inside quoted dialogue).
        /// </summary>
        public static bool IsPermissiveColloquialVariant(ProofingIssue issue, bool isQuotedDialogueOnly = false)
        {
            if (issue == null)
                return false;

            string origNorm = UnicodeNormalizer.NormalizeCanonicalOrder((issue.OriginalText ?? string.Empty).Trim());
            if (string.IsNullOrEmpty(origNorm))
                return false;

            string topFix = (issue.Suggestions != null && issue.Suggestions.Count > 0)
                ? UnicodeNormalizer.NormalizeCanonicalOrder((issue.Suggestions[0].Replacement ?? string.Empty).Trim())
                : string.Empty;

            // 1. Quoted speech ("...") in GeneralStandard tolerates natural spoken contractions: 'တခု', 'တကောင်', 'တယောက်', 'ကျနော်', 'ကျမ', 'ဒါပေမယ့်'
            if (issue.IssueType == ProofingIssueType.NumeralClassifierError &&
                origNorm.StartsWith("တ", StringComparison.Ordinal) &&
                !origNorm.StartsWith("တစ်", StringComparison.Ordinal) &&
                topFix.StartsWith("တစ်", StringComparison.Ordinal))
            {
                return true;
            }

            if (origNorm == "ကျနော်" || origNorm == "ကျမ" ||
                origNorm == "ဒါပေမယ့်" || origNorm == "သို့ပေမယ့်" || origNorm == "ပေမယ့်")
            {
                return true;
            }

            if (isQuotedDialogueOnly)
                return false;

            // 2. Full ColloquialPermissive mode also tolerates widespread web/legacy-keyboard lookalikes ('စျေး' vs 'ဈေး', 'သြ' vs 'ဩ', 'ယောကျာ်း', Pali tall-AA)
            if (PermissiveColloquialExactWords.Contains(origNorm))
                return true;

            if (issue.IssueType == ProofingIssueType.LookalikeCharacterError)
            {
                if ((origNorm.Contains("\u1005\u103B") && topFix.Contains("\u1008")) || // စျေး -> ဈေး
                    (origNorm.Contains("\u101E\u103C") && topFix.Contains("\u1029")) || // သြ -> ဩ
                    (origNorm.IndexOf('\u1039') >= 0 && origNorm.IndexOf('\u102B') >= 0 && topFix.IndexOf('\u102C') >= 0)) // Pali tall-AA pat-sint variants
                {
                    return true;
                }
            }

            return false;
        }

        /// <summary>
        /// Precomputes a boolean character mask marking code units inside balanced Burmese/English quotation marks ("...", “...”, ‘...’).
        /// Unclosed quotes are ignored so stray punctuation never masks an entire paragraph.
        /// </summary>
        public static bool[]? BuildQuotedDialogueMask(string text)
        {
            if (string.IsNullOrEmpty(text) || text.Length < 4)
                return null;

            bool hasQuote = false;
            for (int i = 0; i < text.Length; i++)
            {
                char c = text[i];
                if (c == '"' || c == '\u201C' || c == '\u201D')
                {
                    hasQuote = true;
                    break;
                }
            }
            if (!hasQuote)
                return null;

            bool[]? mask = null;
            int openIdx = -1;
            char expectedClose = '\0';

            for (int i = 0; i < text.Length; i++)
            {
                char c = text[i];
                if (openIdx < 0)
                {
                    if (c == '\u201C')
                    {
                        openIdx = i;
                        expectedClose = '\u201D';
                    }
                    else if (c == '"')
                    {
                        openIdx = i;
                        expectedClose = '"';
                    }
                }
                else if (c == expectedClose || (expectedClose == '\u201D' && c == '"'))
                {
                    if (i - openIdx >= 2 && i - openIdx <= 260)
                    {
                        mask ??= new bool[text.Length];
                        for (int k = openIdx + 1; k < i; k++)
                            mask[k] = true;
                    }
                    openIdx = -1;
                }
                else if (c == '\n' || c == '\r')
                {
                    openIdx = -1;
                }
            }

            return mask;
        }
